/**
 * **サーバ層が組み立てる `ValidationError`**(`V5-M28-T02`。`A-G1` /
 * [`ADR-0249`](../../docs/adr/0249-view-action-audience-write-wall.md))。
 *
 * ## このファイルが在る理由(**先に、正直に書く**)
 *
 * **`src/server/app.ts` には今日すでに 20 本以上の `…Error()` 組み立て関数が並んでいる**
 * (`forbiddenDirectCreateError` / `forbiddenFieldWriteError` など)。**本ファイルはその
 * 慣習から外れた場所である** —— **`V5-M28` の発注書(`docs/plan/v5/records/v5-m28.md`
 * §6-2 `T02`)が「403 用のエラーを `src/server/errors.ts` に1本足す」と名指ししたので、
 * その1本だけをここに置いた。** **既存の組み立て関数を1本も移していない。**
 *
 * ## ここに書いてよいもの / 書いてはならないもの
 *
 * - **書いてよいのは、判定の結果を HTTP の応答文に翻訳することだけである。**
 * - **判定そのものを書いてはならない** —— **壁の導出も合成もロールの突き合わせも
 *   `src/server/owner-scope.ts` の1本が持つ**(`ADR-0249` 限定6)。
 * - **したがって本ファイルは権限の宣言を1度も読まない。** **マニフェストも受け取らない。**
 */
import type { ValidationError } from "../kernel/index.ts";
import {
  MAX_REPORT_GROUPS,
  MAX_REPORT_SCANNED_ROWS,
  type ReportLimitKind,
} from "./report-limits.ts";

// **【`V8-M20` / `J-G29`】`forbiddenViewActionWriteError`(操作起点の「見せる相手」から立った
// 書込の壁による 403)を撤去した。** **`ViewActionWriteKind` の import も同時に消えた** ——
// **本ファイルはもう `owner-scope.ts` から1つも import していない。**
//
// **代わりに立つのは `src/server/app.ts` の `forbiddenRoleAccessError`** ——
// **役割 x 対象(表)x 書込 と 役割 x 対象(ボタン)x 読取。**
// **手続きは `ADR-0301`(語彙を廃止する判定値)。**

/**
 * **引き継ぎを辿るときの上限に当たったので、判定を出せなかった**(400)。
 * `Z-G17` / `V7-M4-T04`。
 *
 * **判定そのものは `owner-scope.ts` の1本が持つ**(上の「書いてよいもの / 書いてはならない
 * もの」の逐語)—— **ここにあるのは、判定の結果を HTTP の応答文に翻訳することだけである。**
 * **受け取るのは上限の種別1つだけで、マニフェストも行も相手も1つも受け取らない。**
 *
 * **【これは「見えない」ではない】** —— **上限に当たった状態と「本当に見えない」状態は、
 * 応答の形で区別できる。** **前者は本エラー(4xx + 上限の種別)で、後者は 404 か
 * 一覧から落ちるだけでエラー本文を持たない**(`v7-m0.md` §6-4b の3)。
 *
 * **【禁止。この上限を「性能上の都合」と書かない】** —— **置く理由は、黙った打ち切りが
 * 「隠れた行がある」と区別できないからである**(`v7-m0.md` §5-5 (b))。
 *
 * **【文面の作法】** —— **内部の記号を利用者向けの文面に1つも出さない**
 * (項目のIDも関数名も審査単位の記号も書かない)。**上限の種別は「段数」か「件数」かが
 * 日本語で読み取れる形で書く。**
 *
 * **【文面で誇張しない】**
 *  - **止まったのはこの1本の要求だけである。** **行は1件も消えていないし、権限も
 *    1つも変わっていない。**
 *  - **上限の値をマニフェストから知る方法は今日1つも無い**(上限は `src/server/` の定数で
 *    あって語彙ではない)。**したがって hint に「上限を設定で変えられます」とは書かない。**
 */
export function recordAccessLimitError(limit: "depth" | "rows"): ValidationError {
  const what = limit === "depth" ? "たどる段数" : "たどって読む行の件数";
  return {
    path: "",
    message: `引き継ぎの上限を超えているため判定できません(${what}の上限に達しました)。`,
    hint:
      limit === "depth"
        ? "権限を引き継ぐ親子関係の段数が深すぎます。親をたどる段数が浅くなるように表の作りを見直してください。"
        : "権限を引き継ぐ親をたどる途中で読む行が多すぎます。親の側の権限の記録や利用者の登録が増えすぎていないか見直してください。",
  };
}

/**
 * **集計表が読取時の上限に当たったので、計算できなかった**(400)。
 * `Q-G17` / `Q-G18` / `Q-G19` / `V8-M10-T05`。
 *
 * **上限そのものは `src/server/report-limits.ts` の定数2本が持つ** —— **ここにあるのは、
 * その結果を HTTP の応答文に翻訳することだけである**(本ファイルの冒頭の逐語)。
 * **受け取るのは上限の種別1つだけで、マニフェストも行も表IDも1つも受け取らない。**
 *
 * **【「どの表か」を1バイトも書かない】**(`v8-m10.md` §1-0c の決定2 の 1')——
 * **群にまとめる前に読む行は、可視性の**前**に数えている。** **表の名前を載せると、
 * 要求した人には1行も見えない表の行数が、上限のエラーとして観測できてしまう。**
 * **したがって載せるのは上限の種別だけである。**
 *
 * **【これは「見えない」でも「0件」でもない】** —— **本当に0件のときは 200 で
 * 合計0・件数0・群0 が返る**(`D-V8-128`)。**上限は 400 で `errors` を持つので、
 * 両者は機械的に区別できる。**
 *
 * **【上限の実数を文面に書く】** —— **同じファイルの `recordAccessLimitError`(引き継ぎの
 * 上限)は実数を1つも書いていない。** **こちらは書いている** —— **理由は、集計表の上限が
 * 「絞り込みを足せば避けられる」種類のものであり、**あと何件まで縮めればよいか**が
 * 分からないと直しようがないからである。** **`recordAccessLimitError` の文面は
 * 1バイトも変えていない**(あちらは表の作りを変える話であって、件数を縮める話ではない)。
 * **どちらも「上限を設定で変えられます」とは書かない** —— **上限は `src/server/` の定数で
 * あって語彙ではなく、宣言から変える手だては今日1つも無い。**
 */
export function reportLimitError(kind: ReportLimitKind): ValidationError {
  if (kind === "groups") {
    return {
      path: "",
      message: `集計の上限を超えているため計算できません(まとめた群の数が上限 ${MAX_REPORT_GROUPS} 件を超えました)。`,
      hint: "束ねるキー(group_by)を、行そのもの(_id)ではなく区分や日付などの束ねられる項目に変えるか、絞り込み(filter)で対象を狭めてください。",
    };
  }
  return {
    path: "",
    message: `集計の上限を超えているため計算できません(群にまとめる前に読む行の件数が上限 ${MAX_REPORT_SCANNED_ROWS} 件を超えました)。`,
    hint: "絞り込み(filter)で対象を狭めるか、集計する範囲を分けてください(1つの集計表が読む行は表ごとに上限があります)。",
  };
}
