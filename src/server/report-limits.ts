/**
 * **集計表が読取時に当たる上限**(`V8-M10-T05`。台帳 `Q-G17` / `Q-G18` / `Q-G19`。
 * 裁定 `M7-1` + ユーザ決定 `D-V8-124`。`v8-m10.md` §1-0c の決定2 / 決定3 / 決定4)。
 *
 * ## 上限は4つあり、**このファイルは後ろ2つだけ**を持つ
 *
 * | 上限 | 値 | どこで止まるか |
 * |---|---:|---|
 * | 結合する表の本数(起点を含む) | **5** | **apply 時**(`src/kernel/referential-integrity.ts` の類型18b) |
 * | 段数(参照の鎖を辿る回数) | **3** | **apply 時**(同上) |
 * | **群にまとめる前に読む行の件数** | **10,000** | **読取時**({@link MAX_REPORT_SCANNED_ROWS}) |
 * | **作る群の数** | **10,000** | **読取時**({@link MAX_REPORT_GROUPS}) |
 *
 * **【禁止】この4値を「測って決めた」と書かない** —— **測ったのは読む行数の1つだけである**
 * (`v8-m7.md` §10-3 の2)。**残る3つは借用と据え置きである。**
 *
 * ## なぜ `src/server/owner-scope.ts` に置かなかったのか(**決めた理由**)
 *
 * **読取時の上限は今日4本ある** —— **本ファイルの2本と、`owner-scope.ts` の
 * `MAX_RECORD_ACCESS_INHERIT_DEPTH`(段数5)/ `MAX_RECORD_ACCESS_INHERIT_ROWS`(行1000)。**
 * **同じファイルに並べたほうが探しやすいのは確かだが、そうしなかった。**
 *
 * 1. **`owner-scope.ts` は「誰に何が見えるか」の判定の集約先である**(`ADR-0061` 限定4)。
 *    **本ファイルの2本は可視性を1ミリも見ない** —— **見るのは行の**数**だけで、
 *    マニフェストも行も要求者も1つも受け取らない。** **性質の違う条文を同じ集約先に
 *    混ぜると、「あそこに在るものは判定である」という読みが崩れる。**
 * 2. **`owner-scope.ts` には凍結基準が掛かっている**(`ADR-0053` 限定4。
 *    `web/test/shell-navigation-boundary.test.ts` が `bytes` と `sha256` を固定している)。
 *    **判定でないものを足すために凍結を1度動かすのは、手続きの意味を薄める。**
 * 3. **`src/kernel/report.ts` にも置けない** —— **公開識別子が1つ増えると
 *    `scripts/kernel-export-snapshot.txt`(`Δ8`)が動く。** **`V8-M10` は語彙を増やさない。**
 * 4. **`src/server/app.ts` に直に数値を埋めない** —— **7,000 行のルート表の中に上限の実数が
 *    埋もれると、`T05b`(上限の実数を配る先を全件列挙する)が数え上げる先を見つけられない。**
 *
 * ## 上限は **inclusive** である(`v8-m10.md` §1-0c の決定3)
 *
 * **その値ちょうどは通り、超えたときだけ 4xx になる。**
 * **`V8-M7` の裁定にこの区別は書かれていない** —— **`T07`(群が上限ちょうどのときの応答の
 * 大きさを測る)が測れる形にするために、`V8-M10` が決めた。**
 *
 * ## 上限は**表ごと**である(`v8-m10.md` §1-0c の決定4)
 *
 * **合計の上限を1つも置いていない。** **結合できる表は起点を含めて5本なので、
 * **5 × 10,000 = 50,000 行がメモリに乗りうる。** **これは事実であって、隠さない。**
 * **さらに逆方向(一対多)の結合が1本入ると、結合した行はその両方の和にまで膨らむ**
 * (**最大およそ 20,000 行**)—— **結合後のファンアウト行数は数えていない**(決定2)。
 *
 * ## このファイルが**しない**こと
 *
 * - **判定を1つも書かない**(誰に何が見えるかを知らない)。
 * - **文面を1つも持たない** —— **HTTP の応答文への翻訳は `src/server/errors.ts` の
 *   `reportLimitError` が持つ**(判定と翻訳を分ける既存の作法)。
 * - **上限を宣言可能にしない** —— **`schemas/` に1バイトも出さない**(`Z-G17` の門外と
 *   同じ扱い)。**その対価は、アプリを作る人が上限をマニフェストから読めないことである。**
 */

/**
 * **群にまとめる前に読む行の件数の上限**(**表ごと**)。
 *
 * **数えるのは表ごとに2箇所である**(`v8-m10.md` §1-0c の決定2):
 *  - **(i) DB から読んだ生の行数**(**可視性の前**)。**ここで止めないと、上限が守る対象
 *    (メモリと時間)を1ミリも守らない** —— **可視性の判定そのものが行の数だけ働くからである。**
 *  - **(ii) 可視性の post-filter を通した後の行数。**
 *
 * **【正直に書く】(ii) は今日1度も発火しない** —— **可視性は行を増やさないので
 * `(ii) ≤ (i)` が常に成り立ち、(i) が同じ値で先に返す。**
 * **それでも書いてあるのは、決定2 が「2箇所で数える」と定めたからであり、
 * (i) を緩めた日に (ii) が最後の歯止めになるためである。**
 *
 * **【(i) で当たったときは「どの表か」を応答に載せない】** —— **載せると、
 * 要求した人には1行も見えない表の行数が、上限のエラーとして観測できてしまう。**
 * **載せるのは上限の種別だけである**(`errors.ts` の `reportLimitError`)。
 */
export const MAX_REPORT_SCANNED_ROWS = 10000;

/**
 * **1つの集計表が作る群の数の上限。**
 *
 * **【正直に書く】数えているのは「作り終えたあと」である** —— **群を作る途中で
 * 打ち切っていない。** **`src/kernel/report.ts` に判定も上限も1文字も置かない
 * (`v8-m10.md` §1-0c の決定1 と同じ向き)ことを優先した結果である。**
 * **メモリの上では、行の上限が先に効いている** —— **群の数は結合した行の数を超えないので、
 * 表ごとの 10,000 と「逆方向の結合は1本まで」(apply 時に閉じてある)から、
 * 群の数はおよそ 20,000 を超えない。**
 */
export const MAX_REPORT_GROUPS = 10000;

/** 上限の種別。**応答の文面を選ぶのはこの1つだけである。** */
export type ReportLimitKind = "scanned_rows" | "groups";

/**
 * **群にまとめる前に読む行の件数が上限を超えたか**(**inclusive**: ちょうどは超えない)。
 */
export function exceedsReportScannedRows(rows: number): boolean {
  return rows > MAX_REPORT_SCANNED_ROWS;
}

/** **作る群の数が上限を超えたか**(**inclusive**: ちょうどは超えない)。 */
export function exceedsReportGroups(groups: number): boolean {
  return groups > MAX_REPORT_GROUPS;
}
