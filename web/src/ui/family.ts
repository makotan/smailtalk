/**
 * 見た目の器の**系統**(V4-M15-T18。ユーザ決定 `D-V4-59`)。
 *
 * ## これは何で、何ではないか
 *
 * **`V4-M14` は `P-G26`(AI が既製の部品名で指定できるようにする)を却下した。**
 * 却下の理由は「**選べる対象(見た目の器)が2つ以上実在しないうちは、選べるという
 * 言葉を語彙に増やす意味がない**」である。`D-V4-59` はそれを受けて
 * 「**部品を複数用意してから再提出**」と決めた。
 *
 * **本ファイルが作るのは「選べる対象が2つ以上実在する状態」だけである。**
 *
 * - **【禁止】これを「AI が部品を選べるようになった」と書かない。** 今日は選べない。
 * - **`ADR-0087` 限定2 を破らない** —— **系統の選択はマニフェストに1バイトも現れない。**
 *   `schemas/` に1バイトも触っていない。差分操作も語彙も1つも増えていない。
 * - **切り替えの手段はマニフェストの外にある**(下の `resolveUiFamily`)。
 *
 * ## 2つの系統
 *
 * | 系統 | 何が違うか |
 * |---|---|
 * | `comfortable`(既定) | 部品体系(shadcn/ui)の既定の密度。ボタンの高さ 2.25rem、表のセルの上下余白 `--space-2`、角丸はスロットの値そのまま |
 * | `compact` | 密度を上げた系統。ボタンの高さ 1.75rem、表のセルの上下余白 `--space-1`、角丸を 0 に潰し、文字を1段小さくする |
 *
 * **どちらの系統も、色は同じ25スロットから導出する**(`ADR-0087` 限定7)。
 * **系統が変えるのは密度・角丸・文字の大きさだけであり、配色は1つも変えない。**
 *
 * ## どこで切り替わるか(3つ。すべてマニフェストの外)
 *
 * 1. **ビルド時の環境変数** `VITE_ST_UI_FAMILY`(`comfortable` / `compact`)。
 * 2. **実行時のテスト用の口** `globalThis.__ST_UI_FAMILY__`。
 *    `web/test` と `web/e2e`(`page.addInitScript`)がこれを使う。
 * 3. どちらも無ければ `DEFAULT_UI_FAMILY`。
 *
 * **owner にも AI にも、この3つのどれにも触る口を画面上に出していない。**
 *
 * ## **【`V4-M19-T03` / `T04` / `ADR-0118` で偽になった。旧文を1バイトも消していない】**
 *
 * **上の「3つ。すべてマニフェストの外」と、冒頭の「本ファイルが作るのは『選べる対象が
 * 2つ以上実在する状態』だけである」「今日は選べない」は、2026-08-04 以降は成り立たない。**
 * **門A の本審査(`V4-M19` 単位C。判定 = 限定採用)が `$defs/view` に `preset_density` を
 * 通し、`V4-M19-T04` が当たり先を画面ごとに広げた。**
 *
 * **したがって切り替えの手段は4つになり、いちばん強いのはマニフェストの宣言である** ——
 * **画面の宣言 → テスト用の口 → ビルド時の環境変数 → 既定。**
 *
 * - **【禁止】これを「AI が部品を選べるようになった」と読まない**(`ADR-0118` §Decision 5)——
 *   **選べるのは詰まり具合の2値だけで、部品も器も1つも選べない**(`P-G26` は4回却下されている)。
 * - **`ADR-0087` 限定2(系統の選択はマニフェストに1バイトも現れない)は今日から成り立たない。**
 *   **その事実を本ファイルの側にだけ書いた** —— **`ADR-0087` の本文を1バイトも書き換えていない。**
 */

export const UI_FAMILIES = ["comfortable", "compact"] as const;

export type UiFamily = (typeof UI_FAMILIES)[number];

export const DEFAULT_UI_FAMILY: UiFamily = "comfortable";

function isUiFamily(value: unknown): value is UiFamily {
  return typeof value === "string" && (UI_FAMILIES as readonly string[]).includes(value);
}

/**
 * いまの系統を決める。**判定はここ1箇所だけである**(2箇所に住むと食い違う)。
 *
 * 読む順は「**画面の宣言** → テスト用の口 → ビルド時の環境変数 → 既定」。
 * **読めない値・知らない値は既定に倒す**(fail-closed。落ちない)。
 *
 * ## **【`V4-M19-T04` / `ADR-0118` 限定7 で引数を1つ足した】**
 *
 * **上の「切り替えの手段はマニフェストの外にある」という記述は、今日から成り立たない** ——
 * **`ADR-0118`(門A / 判定 = 限定採用)が `$defs/view` に `preset_density` を通したので、
 * 画面ごとの宣言がマニフェストの中に在る。** **旧文を1バイトも消していない。**
 *
 * **限定7 の逐語**: 「**マニフェスト由来の値も、実行時の口も、ビルド時の環境変数も、
 * 既定も、すべて同じ1つの関数を通す。2箇所目を作らない。**」 —— **だから引数で受ける。**
 * **呼び出し側で `?? DEFAULT_UI_FAMILY` のような判定を書かない**(それは2箇所目である)。
 *
 * **宣言はテスト用の口とビルド時の環境変数より強い** —— **「その画面はこれ」とアプリが
 * 書いているなら、それがその画面の答えである。** **宣言を持たない画面は今日どおり
 * 「テスト用の口 → 環境変数 → 既定」で決まり、DOM は1バイトも変わらない**(限定8)。
 *
 * **【この関数が解かないこと】** **返すのは「その画面の系統」だけである。**
 * **アプリ全体が `compact` のときに画面で `comfortable` へ戻すことはできない** ——
 * 当たり先の `group-data-[ui-family=compact]/ui:` は「**祖先のどれかが `compact`**」で
 * 当たるためで、内側に `comfortable` を立てても外側を打ち消せない。
 * **実測は `web/test/view-density.test.tsx` の (T04-6) が固定している。隠さない。**
 */
export function resolveUiFamily(declared?: unknown): UiFamily {
  if (isUiFamily(declared)) {
    return declared;
  }
  const hook = (globalThis as { __ST_UI_FAMILY__?: unknown }).__ST_UI_FAMILY__;
  if (isUiFamily(hook)) {
    return hook;
  }
  const fromEnv = import.meta.env?.VITE_ST_UI_FAMILY;
  if (isUiFamily(fromEnv)) {
    return fromEnv;
  }
  return DEFAULT_UI_FAMILY;
}
