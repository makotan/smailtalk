/**
 * 書込が権限不足(サーバの 403)で拒否されたことの表示(V1-M3-T02)。
 *
 * viewer には書込 UI を先回りで出さないが、ロールがサーバ側で変わった直後などに
 * 403 が返ることはある。そのとき「セッションが切れた(401)」ではなく
 * 「ログイン済みだが権限が無い」ことを明示するための共通表示(form / detail が使う)。
 *
 * ## 【V4-M15-T14】器を部品体系の `Alert` に載せ替えた(`ADR-0087`)
 *
 * **理由と、変えていないものの一覧は `WriteConflict.tsx` の冒頭と同じである**
 * (文言・`data-testid`・`class` を1つも動かしていない。`role="alert"` は `Alert` が持つ)。
 * **要素は `<p>` から `<div>` に変わる。隠さない。**
 */
import { Alert } from "../ui/surfaces.tsx";
import { cn } from "../ui/utils.ts";

/**
 * **【`V23-M12-T05b`。決定 `D-V23-418`・`D-V23-419`】入力画面の 403 で本文を出してよい文の一覧(許可の一覧)。**
 *
 * 本体のサーバが入力画面(作成と更新の口)に返しうる 403 の文のうち、内部の綴り(欄の ID・表の ID・層の名・
 * 道具の名など)が混じらない文だけを、文ごとに丸ごと並べる。 ここに当たらない文は今日の一律の文
 * 「権限がありません(閲覧のみ)。」にする(見分けの綴りを否定する形にしない。 知らない文も一律の文に倒れる)。
 * 一覧と本体の文の突き合わせは `web/test/app-rejected-message.test.tsx` の `V23-M12-T05b` の節が見張る。
 * 書き出す版(生成器 `src/emit.ts` の `FORM_FORBIDDEN_SHOWN_SOURCES`)も同じ並びを焼く(生成器の
 * `parity-create-gate.test.ts` が本ファイルの並びと突き合わせる)。
 */
export const FORM_FORBIDDEN_SHOWN_TEXTS: readonly RegExp[] = [
  /^この表はアプリの中の記録のために製品が使う表なので、書き換えられません。$/u,
  /^ほかの利用者を持ち主にした登録はできません。$/u,
  /^この表に行を作れる立場が決められており、あなたの立場はそこに挙がっていないため、行を作れません。$/u,
  /^この表に行を作れる立場が一行も決められていないため、今はどなたも行を作れません。$/u,
  /^この表の行は、元になる行に書き込める人だけが作れます。あなたには、指定された元の行を書き換える権限がありません。$/u,
  /^この表の行は、元になる行に対してアプリが決めた種類の権限を持つ人だけが作れます。あなたは元になる行を書き換えられますが、その種類の権限を持っていません。$/u,
  /^この行を別の元の行へ移すには、移す前の元の行を消せる必要があります。あなたには、移す前の元の行を消す権限がありません\(移す前の元の行に書き込めるだけでは移せません\)。$/u,
  /^この表の行は、元になる行の側で「誰が何をできるか」が決められていないため、今は誰も作れません。$/u,
  /^(この行に権限を付けられる|この行の権限を変えられる|この行の権限を外せる)のは、(この行で「[^「」]+」(か「[^「」]+」)*の権限を持つ人と運営者|アプリの運営者)だけです。$/u,
  /^自分に権限を付けることはできません。$/u,
  /^この相手は、元になっている行を見る権限を持っていないため、ここには追加できません。$/u,
  /^相手の行を指す欄は、招待の承諾でだけ書けます。$/u,
  /^(参加者|グループ)の表は、アプリの運営者だけが書き換えられます。$/u,
  /^参加者の表で書き換えられるのは、自分の行の名前だけです。ほかの欄と、ほかの人の行は、アプリの運営者だけが書き換えられます。$/u,
];

/** 入力画面の 403 の文が、本文を出してよい文の一覧に当たるか(`D-V23-418`)。 */
export function formForbiddenTextShown(text: string): boolean {
  return FORM_FORBIDDEN_SHOWN_TEXTS.some((pattern) => pattern.test(text));
}

/**
 * **【`V23-M12-T05`。決定 `D-V23-360` の (4)・`D-V23-398`・`D-V23-406`・`D-V23-413` の (1)】**
 * 断りの本文の文(`message`)を渡されたら、一律の文の代わりにそれを出す(添える文 `hint` は出さない —— 内部の
 * 道具の名を含むことがあるため)。 渡されない・空なら今日の一律の文。 どの断りの本文を渡すかは呼び手が決める
 * (入力画面は層の名が混じる断りでは渡さない)。 器(`data-testid`・`class`)は1つも変えていない。
 * 旧の宣言(逐語): `export function WriteForbidden() {`
 */
export function WriteForbidden({ messages }: { messages?: readonly string[] } = {}) {
  const shown = (messages ?? []).filter((message) => message !== "");
  return (
    <Alert variant="destructive" className={cn("write-forbidden")} data-testid="write-forbidden">
      {shown.length === 0 ? "権限がありません(閲覧のみ)。" : shown.join(" ")}
    </Alert>
  );
}
